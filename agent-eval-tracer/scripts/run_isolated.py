def _demo():
    """Standard Synchronous Agent Demo."""
    import random

    def fake_routing_agent(test_input, *, temperature=0.0):
        spy = ToolSpy("emit_route", returns=None)
        confidence = test_input["confidence"]
        # Deterministic core decision...
        if confidence >= 0.5:
            route = "handle"
        elif confidence < 0.4:
            route = "escalate"
        else:
            # ...except in the 0.4–0.5 band, where temperature makes it wobble.
            route = random.choice(["handle", "escalate"]) if temperature > 0 else "handle"
        spy(route)
        return {
            "output": {"route": route, "confidence": confidence},
            "reasoning": f"confidence={confidence} → {route}",
            "tool_calls": spy.calls,
            "error": None,
        }

    inputs = [
        {"id": "clear_handle",   "value": {"confidence": 0.92}},
        {"id": "clear_escalate", "value": {"confidence": 0.20}},
        {"id": "boundary_band",  "value": {"confidence": 0.45}},  # the unstable one
    ]
    recs = run_suite("routing_demo", fake_routing_agent, inputs,
                     repeats=5, regimes=[0.0, 0.7], out_path="runs_demo.jsonl")
    print(f"\n[Sync Demo] ran {len(recs)} records. Sample:")
    for rec in recs[:3]:
        print(" ", rec.input_id, "t=%.1f" % rec.temperature, "->", rec.output, f"({rec.duration_ms}ms)")
    print("\nNow score them:  python consistency.py runs_demo.jsonl")


def _demo_async():
    """Asynchronous & Streaming Agent Demo."""
    import random

    async def fake_async_streaming_agent(test_input, *, temperature=0.0):
        # Demonstrate dynamic ToolSpy callback
        def user_lookup(uid):
            return {"user_id": uid, "tier": "vip" if uid > 500 else "standard"}

        spy = ToolSpy("user_lookup", handler=user_lookup)
        user_info = spy(test_input["user_id"])

        await asyncio.sleep(0.01)  # Simulate async I/O

        category = "priority" if user_info["tier"] == "vip" else "standard"
        if temperature > 0 and random.random() < 0.2:
            category = "manual_review"  # Slight drift at temp > 0

        return {
            "output": {"category": category, "tier": user_info["tier"]},
            "reasoning": f"user={test_input['user_id']} tier={user_info['tier']} -> {category}",
            "tool_calls": spy.calls,
            "error": None,
        }

    inputs = [
        {"id": "vip_user",      "value": {"user_id": 888}},
        {"id": "standard_user", "value": {"user_id": 120}},
    ]
    recs = run_suite("async_demo", fake_async_streaming_agent, inputs,
                     repeats=3, regimes=[0.0, 0.7], timeout_seconds=5.0,
                     out_path="runs_demo_async.jsonl")
    print(f"\n[Async Demo] ran {len(recs)} async records. Sample:")
    for rec in recs[:3]:
        print(" ", rec.input_id, "t=%.1f" % rec.temperature, "->", rec.output, f"({rec.duration_ms}ms)")
    print("\nNow score them:  python consistency.py runs_demo_async.jsonl")


def _demo_resilience():
    """Timeout & Exponential Backoff Retry Demo."""
    call_counts = {"attempts": 0}

    def flaky_agent(test_input, *, temperature=0.0):
        call_counts["attempts"] += 1
        if test_input.get("hang"):
            time.sleep(0.5)  # Will exceed 0.1s timeout
            return {"output": "finished late", "tool_calls": []}

        # Simulate 429 rate limit on first attempt, then recover
        if call_counts["attempts"] == 1:
            raise RuntimeError("HTTP 429: Too Many Requests (Rate limit exceeded)")
        return {"output": "recovered after retry", "tool_calls": []}

    inputs = [
        {"id": "rate_limited_case", "value": {"hang": False}},
        {"id": "timeout_case",      "value": {"hang": True}},
    ]
    print("\n[Resilience Demo] Running suite with timeout=0.1s and max_retries=2...")
    recs = run_suite("resilience_demo", flaky_agent, inputs,
                     repeats=1, regimes=[0.0], timeout_seconds=0.1, max_retries=2)
    for rec in recs:
        status = "ERROR" if rec.error else "OK"
        err_msg = f"({rec.error.strip().splitlines()[-1]})" if rec.error else ""
        print(f"  {rec.input_id}: [{status}] output={rec.output} {err_msg}")


