#!/usr/bin/env python3
"""
run_isolated.py — run ONE agent in isolation, N times per input, capturing the
full trace (reasoning + tool calls + output + timing) to a runs file.

This is a framework-agnostic harness. You do NOT edit this file to plug in your
agent. Instead you write a tiny *adapter* (see references/isolation.md) that maps
your real agent onto the AgentAdapter interface below, wiring in spies for every
side-effecting tool and freezing the agent's upstream input. This harness then
handles the repetitive part: repeated running, both temperature regimes, error
capture, timing, and writing runs to disk.

USAGE AS A LIBRARY (the normal case)
------------------------------------
    from run_isolated import ToolSpy, run_suite

    def adapter(test_input, *, temperature=0.0):
        spy = ToolSpy("db_write", returns={"ok": True})
        agent = build_your_real_agent(tools={"db_write": spy},
                                      temperature=temperature)
        result = agent.run(test_input)
        return {
            "output":     result.output,
            "reasoning":  getattr(result, "reasoning", None),
            "tool_calls": spy.calls,
            "error":      None,
        }

    run_suite(
        agent_name="routing",
        adapter=adapter,
        inputs=[{"id": "normal",   "value": {...}},
                {"id": "boundary", "value": {...}}],
        repeats=5,
        regimes=[0.0, 0.7],
        out_path="runs/routing.jsonl",
    )

DEMO
----
    python run_isolated.py --demo
Runs a built-in fake agent so you can see the output shape without wiring
anything up.
"""
from __future__ import annotations

import argparse
import json
import time
import traceback
from dataclasses import dataclass, field, asdict
from typing import Any, Callable, Dict, List, Optional


# --------------------------------------------------------------------------- #
# Spy: replaces a side-effecting tool. Records the call, performs nothing real.
# --------------------------------------------------------------------------- #
class ToolSpy:
    """A stand-in for a real tool. Records every call and returns a canned value
    instead of performing the real side effect. Reset per run so call lists don't
    leak between repeats."""

    def __init__(self, name: str, returns: Any = None):
        self.name = name
        self.returns = returns
        self.calls: List[Dict[str, Any]] = []

    def __call__(self, *args, **kwargs):
        self.calls.append({"tool": self.name, "args": args, "kwargs": kwargs})
        return self.returns

    def reset(self):
        self.calls = []


# --------------------------------------------------------------------------- #
# The interface your adapter must satisfy, and the record we store per run.
# --------------------------------------------------------------------------- #
# AgentAdapter: Callable[[test_input_value, *, temperature: float], dict]
# The returned dict should contain: output, reasoning, tool_calls, error.
AgentAdapter = Callable[..., Dict[str, Any]]


@dataclass
class RunRecord:
    agent_name: str
    input_id: str
    temperature: float
    repeat_index: int
    output: Any = None
    reasoning: Any = None
    tool_calls: List[Dict[str, Any]] = field(default_factory=list)
    error: Optional[str] = None
    duration_ms: float = 0.0


def _run_once(agent_name: str, adapter: AgentAdapter, input_id: str,
              input_value: Any, temperature: float, repeat_index: int) -> RunRecord:
    start = time.perf_counter()
    rec = RunRecord(agent_name=agent_name, input_id=input_id,
                    temperature=temperature, repeat_index=repeat_index)
    try:
        result = adapter(input_value, temperature=temperature)
        rec.output = result.get("output")
        rec.reasoning = result.get("reasoning")
        rec.tool_calls = result.get("tool_calls") or []
        rec.error = result.get("error")
    except Exception:  # the agent raised — capture, don't crash the suite
        rec.error = traceback.format_exc()
    rec.duration_ms = round((time.perf_counter() - start) * 1000, 2)
    return rec


def run_suite(agent_name: str,
              adapter: AgentAdapter,
              inputs: List[Dict[str, Any]],
              repeats: int = 5,
              regimes: Optional[List[float]] = None,
              out_path: Optional[str] = None) -> List[RunRecord]:
    """Run `adapter` over every input, `repeats` times, in each temperature
    regime. Returns the list of RunRecords and (if out_path given) writes them as
    JSON lines.

    inputs: list of {"id": str, "value": Any}. `value` is the FROZEN input for
            this agent — hand-written or recorded once, never live upstream output.
    regimes: temperatures to test. Default [0.0, 0.7] — the determinism check and
             the robustness check. See references/consistency.md.
    """
    if regimes is None:
        regimes = [0.0, 0.7]

    records: List[RunRecord] = []
    for item in inputs:
        input_id = item["id"]
        input_value = item["value"]
        for temperature in regimes:
            for r in range(repeats):
                rec = _run_once(agent_name, adapter, input_id, input_value,
                                temperature, r)
                records.append(rec)

    if out_path:
        with open(out_path, "w", encoding="utf-8") as f:
            for rec in records:
                f.write(json.dumps(asdict(rec), default=str) + "\n")
        print(f"wrote {len(records)} runs to {out_path}")

    return records


# --------------------------------------------------------------------------- #
# Built-in demo: a fake "routing" agent that is mostly stable but wobbles on a
# boundary input, so you can see stable vs unstable output before wiring in real
# agents.
# --------------------------------------------------------------------------- #
def _demo():
    import random

    def fake_routing_agent(test_input, *, temperature=0.0):
        spy = ToolSpy("emit_route", returns=None)
        confidence = test_input["confidence"]
        # Deterministic core decision...
        if confidence >= 0.5:
            route = "handle"
        elif confidence < 0.4:
            route = "escalate"
        else:
            # ...except in the 0.4–0.5 band, where temperature makes it wobble.
            route = random.choice(["handle", "escalate"]) if temperature > 0 else "handle"
        spy(route)
        return {
            "output": {"route": route, "confidence": confidence},
            "reasoning": f"confidence={confidence} → {route}",
            "tool_calls": spy.calls,
            "error": None,
        }

    inputs = [
        {"id": "clear_handle",   "value": {"confidence": 0.92}},
        {"id": "clear_escalate", "value": {"confidence": 0.20}},
        {"id": "boundary_band",  "value": {"confidence": 0.45}},  # the unstable one
    ]
    recs = run_suite("routing_demo", fake_routing_agent, inputs,
                     repeats=5, regimes=[0.0, 0.7], out_path="runs_demo.jsonl")
    print(f"\nran {len(recs)} records. Sample:")
    for rec in recs[:3]:
        print(" ", rec.input_id, "t=%.1f" % rec.temperature, "->", rec.output)
    print("\nNow score them:  python consistency.py runs_demo.jsonl")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--demo", action="store_true", help="run the built-in demo agent")
    args = ap.parse_args()
    if args.demo:
        _demo()
    else:
        ap.print_help()
