#!/usr/bin/env python3
"""
run_isolated.py — run ONE agent in isolation, N times per input, capturing the
full trace (reasoning + tool calls + output + timing) to a runs file.

Supports both SYNCHRONOUS and ASYNCHRONOUS (async/await, streaming) agents with
native timeout protection and exponential backoff retry for rate limits.

This is a framework-agnostic harness. You do NOT edit this file to plug in your
agent. Instead you write a tiny *adapter* (see references/isolation.md) that maps
your real agent onto the AgentAdapter interface below, wiring in spies for every
side-effecting tool and freezing the agent's upstream input. This harness then
handles the repetitive part: repeated running, both temperature regimes, error
capture, timing, and writing runs to disk.

USAGE AS A LIBRARY (Synchronous Agent)
--------------------------------------
    from run_isolated import ToolSpy, run_suite

    def adapter(test_input, *, temperature=0.0):
        spy = ToolSpy("db_write", returns={"ok": True})
        agent = build_your_real_agent(tools={"db_write": spy},
                                      temperature=temperature)
        result = agent.run(test_input)
        return {
            "output":     result.output,
            "reasoning":  getattr(result, "reasoning", None),
            "tool_calls": spy.calls,
            "error":      None,
        }

    run_suite(
        agent_name="routing",
        adapter=adapter,
        inputs=[{"id": "normal",   "value": {...}},
                {"id": "boundary", "value": {...}}],
        repeats=5,
        regimes=[0.0, 0.7],
        out_path="runs/routing.jsonl",
    )

USAGE AS A LIBRARY (Asynchronous / Streaming Agent)
---------------------------------------------------
    async def async_adapter(test_input, *, temperature=0.0):
        spy = ToolSpy("fetch_user", returns={"tier": "gold"})
        agent = build_async_agent(tools={"fetch_user": spy})
        result = await agent.ainvoke(test_input, temperature=temperature)
        return {
            "output": result.output,
            "reasoning": result.thought,
            "tool_calls": spy.calls,
            "error": None,
        }

    run_suite(
        agent_name="async_routing",
        adapter=async_adapter,
        inputs=[{"id": "test_1", "value": {...}}],
        timeout_seconds=10.0,
        max_retries=2,
        out_path="runs/async_routing.jsonl",
    )

DEMOS
-----
    python run_isolated.py --demo              # standard sync demo
    python run_isolated.py --demo-async        # async & streaming agent demo
    python run_isolated.py --demo-resilience   # timeout & retry guardrails demo
"""
from __future__ import annotations

import argparse
import asyncio
import concurrent.futures
import inspect
import json
import re
import time
import traceback
from dataclasses import dataclass, field, asdict
from typing import Any, Callable, Dict, List, Optional, Union


# --------------------------------------------------------------------------- #
# Spy: replaces a side-effecting tool. Records the call, performs nothing real.
# Supports static canned returns or dynamic handlers for multi-step loops.
# --------------------------------------------------------------------------- #
class ToolSpy:
    """A stand-in for a real tool. Records every call and returns a canned value
    (or invokes an optional dynamic callback handler) instead of performing the
    real side effect. Reset per run so call lists don't leak between repeats."""

    def __init__(self, name: str, returns: Any = None, handler: Optional[Callable] = None):
        self.name = name
        self.returns = returns
        self.handler = handler
        self.calls: List[Dict[str, Any]] = []

    def __call__(self, *args, **kwargs):
        self.calls.append({"tool": self.name, "args": args, "kwargs": kwargs})
        if self.handler is not None:
            return self.handler(*args, **kwargs)
        return self.returns

    def reset(self):
        self.calls = []


# --------------------------------------------------------------------------- #
# The interface your adapter must satisfy, and the record we store per run.
# --------------------------------------------------------------------------- #
# AgentAdapter: Callable[[test_input_value, *, temperature: float], Union[dict, Coroutine, AsyncGenerator]]
# The returned dict should contain: output, reasoning, tool_calls, error.
AgentAdapter = Callable[..., Any]


@dataclass
class RunRecord:
    agent_name: str
    input_id: str
    temperature: float
    repeat_index: int
    output: Any = None
    reasoning: Any = None
    tool_calls: List[Dict[str, Any]] = field(default_factory=list)
    error: Optional[str] = None
    duration_ms: float = 0.0
    streaming_chunks: Optional[List[Any]] = None


# --------------------------------------------------------------------------- #
# Resilience: Detect transient errors (Rate limits, 429, timeouts, connection drops)
# --------------------------------------------------------------------------- #
_TRANSIENT_PATTERNS = [
    re.compile(r"429", re.IGNORECASE),
    re.compile(r"rate\s*limit", re.IGNORECASE),
    re.compile(r"tpm|rpm\s*limit", re.IGNORECASE),
    re.compile(r"quota\s*exceeded", re.IGNORECASE),
    re.compile(r"timeout|timed\s*out", re.IGNORECASE),
    re.compile(r"503\s*service\s*unavailable", re.IGNORECASE),
    re.compile(r"connection\s*(reset|refused|closed)", re.IGNORECASE),
    re.compile(r"temporarily\s*unavailable", re.IGNORECASE),
]


def _is_transient_error(error_str: str) -> bool:
    """Return True if the error matches common transient API failure patterns."""
    return any(p.search(error_str) for p in _TRANSIENT_PATTERNS)


# --------------------------------------------------------------------------- #
# Execution Helpers: Sync, Async, Streaming & Timeout Handling
# --------------------------------------------------------------------------- #
async def _consume_async_adapter(adapter: AgentAdapter, input_value: Any, temperature: float) -> Dict[str, Any]:
    """Execute an async coroutine adapter or async generator (streaming)."""
    if inspect.isasyncgenfunction(adapter):
        chunks = []
        async for chunk in adapter(input_value, temperature=temperature):
            chunks.append(chunk)
        # Aggregate text chunks if strings, else keep as structured payload
        if all(isinstance(c, str) for c in chunks):
            full_output = "".join(chunks)
        else:
            full_output = chunks
        return {"output": full_output, "streaming_chunks": chunks, "tool_calls": [], "error": None}

    res = adapter(input_value, temperature=temperature)
    if inspect.isawaitable(res):
        res = await res

    # Handle async generator returned from a regular function
    if hasattr(res, "__aiter__"):
        chunks = []
        async for chunk in res:
            chunks.append(chunk)
        if all(isinstance(c, str) for c in chunks):
            full_output = "".join(chunks)
        else:
            full_output = chunks
        return {"output": full_output, "streaming_chunks": chunks, "tool_calls": [], "error": None}

    return res


def _run_with_timeout_sync(fn: Callable, timeout_seconds: float) -> Any:
    """Execute a synchronous function with cross-platform timeout."""
    with concurrent.futures.ThreadPoolExecutor(max_workers=1) as executor:
        future = executor.submit(fn)
        try:
            return future.result(timeout=timeout_seconds)
        except concurrent.futures.TimeoutError:
            raise TimeoutError(f"Execution timed out after {timeout_seconds:.1f}s")


def _execute_adapter(adapter: AgentAdapter, input_value: Any, temperature: float,
                     timeout_seconds: Optional[float] = None) -> Dict[str, Any]:
    """Universal execution dispatcher handling sync, async, streaming, and timeouts."""
    is_async = (inspect.iscoroutinefunction(adapter) or
                inspect.isasyncgenfunction(adapter))

    if is_async:
        async def _async_runner():
            if timeout_seconds and timeout_seconds > 0:
                return await asyncio.wait_for(
                    _consume_async_adapter(adapter, input_value, temperature),
                    timeout=timeout_seconds
                )
            return await _consume_async_adapter(adapter, input_value, temperature)

        # Run async event loop
        try:
            loop = asyncio.get_event_loop()
            if loop.is_running():
                # In an environment with an active loop (e.g. Jupyter / interactive), run in thread
                with concurrent.futures.ThreadPoolExecutor(max_workers=1) as executor:
                    return executor.submit(asyncio.run, _async_runner()).result()
            else:
                return loop.run_until_complete(_async_runner())
        except RuntimeError:
            return asyncio.run(_async_runner())

    # Synchronous path
    if timeout_seconds and timeout_seconds > 0:
        res = _run_with_timeout_sync(lambda: adapter(input_value, temperature=temperature), timeout_seconds)
    else:
        res = adapter(input_value, temperature=temperature)

    # If sync adapter returned a coroutine / awaitable
    if inspect.isawaitable(res):
        async def _await_res():
            if timeout_seconds and timeout_seconds > 0:
                return await asyncio.wait_for(res, timeout=timeout_seconds)
            return await res
        return asyncio.run(_await_res())

    return res


def _run_once(agent_name: str, adapter: AgentAdapter, input_id: str,
              input_value: Any, temperature: float, repeat_index: int,
              timeout_seconds: Optional[float] = None,
              max_retries: int = 0,
              backoff_factor: float = 1.5) -> RunRecord:
    """Execute a single run with timing, error capture, and exponential backoff retry."""
    start = time.perf_counter()
    rec = RunRecord(agent_name=agent_name, input_id=input_id,
                    temperature=temperature, repeat_index=repeat_index)

    attempts = 0
    while True:
        attempts += 1
        try:
            result = _execute_adapter(adapter, input_value, temperature, timeout_seconds=timeout_seconds)
            rec.output = result.get("output")
            rec.reasoning = result.get("reasoning")
            rec.tool_calls = result.get("tool_calls") or []
            rec.streaming_chunks = result.get("streaming_chunks")
            rec.error = result.get("error")
            break  # Success
        except Exception as exc:
            err_str = traceback.format_exc()
            if attempts <= max_retries and _is_transient_error(str(exc) + " " + err_str):
                delay = (backoff_factor ** attempts) * 0.5
                time.sleep(delay)
                continue
            # Non-transient or exhausted retries: record error and proceed
            rec.error = err_str
            break

    rec.duration_ms = round((time.perf_counter() - start) * 1000, 2)
    return rec


def run_suite(agent_name: str,
              adapter: AgentAdapter,
              inputs: List[Dict[str, Any]],
              repeats: int = 5,
              regimes: Optional[List[float]] = None,
              timeout_seconds: Optional[float] = None,
              max_retries: int = 0,
              backoff_factor: float = 1.5,
              out_path: Optional[str] = None) -> List[RunRecord]:
    """Run `adapter` over every input, `repeats` times, in each temperature
    regime. Returns the list of RunRecords and (if out_path given) writes them as
    JSON lines.

    inputs: list of {"id": str, "value": Any}. `value` is the FROZEN input for
            this agent — hand-written or recorded once, never live upstream output.
    regimes: temperatures to test. Default [0.0, 0.7] — the determinism check and
             the robustness check. See references/consistency.md.
    timeout_seconds: optional execution timeout per run (sync & async).
    max_retries: retry count for transient rate limits (429) or network timeouts.
    backoff_factor: exponential backoff multiplier for retries.
    """
    if regimes is None:
        regimes = [0.0, 0.7]

    records: List[RunRecord] = []
    for item in inputs:
        input_id = item["id"]
        input_value = item["value"]
        for temperature in regimes:
            for r in range(repeats):
                rec = _run_once(
                    agent_name=agent_name,
                    adapter=adapter,
                    input_id=input_id,
                    input_value=input_value,
                    temperature=temperature,
                    repeat_index=r,
                    timeout_seconds=timeout_seconds,
                    max_retries=max_retries,
                    backoff_factor=backoff_factor
                )
                records.append(rec)

    if out_path:
        with open(out_path, "w", encoding="utf-8") as f:
            for rec in records:
                f.write(json.dumps(asdict(rec), default=str) + "\n")
        print(f"wrote {len(records)} runs to {out_path}")

    return records


